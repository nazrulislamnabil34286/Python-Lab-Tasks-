import numpy as np

arr1 = np.array([2, 4, 6, 8])
arr2 = np.array([1, 3, 5, 7])

print("First Array:")
print(arr1)

print("\nSecond Array:")
print(arr2)


print("\nSum of first array:")
print(np.sum(arr1))

print("\nSum of second array:")
print(np.sum(arr2))

print("\nProduct of first array:")
print(np.prod(arr1))

print("\nProduct of second array:")
print(np.prod(arr2))

print("\nDifference of first array:")
print(np.diff(arr1))

print("\nDifference of second array:")
print(np.diff(arr2))