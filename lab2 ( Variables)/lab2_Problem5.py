
num=float(input("Enter student number: "))
if 90<=num<=100:
    print ("The student get A+.")
    
elif 85<=num<=89:
    print ("The student get A.")

elif 80<=num<=84:
    print ("The student get B+.")

elif 75<=num<=79:
    print ("The student get B.")

elif 70<=num<=74:
    print ("The student get C+.")

elif 65<=num<=69:
    print ("The student get C.")
    
elif 60<=num<=64:
    print ("The student get D+.")

elif 50<=num<=59:
    print ("The student get D.")

else:
    print ("The student get Fail(F).")


